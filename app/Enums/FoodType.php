<?php

namespace App\Enums;

enum FoodType: int
{
    case عادي               = 1;  // ما عندي أي مشكلة
    case عالي_البروتين      = 2;  // أبي أزيد بروتين
    case نباتي              = 3;  // أنا نباتي
    case LiverHealth        = 4;  // صحة الكبد
    case السكري             = 5;  // سكري
    case مشاكل_القولون      = 6;  // مشاكل قولون
    case ارتفاع_الكوليسترول = 7;  // ارتفاع كوليسترول
    case فقر_الدم           = 8;  // فقر دم / نقص حديد
    case التصلب_المتعدد     = 9;  // تصلب متعدد (MS)
    case برنامج_٢١_يوم      = 10; // برنامج 21 يوم
    case جرثومة_المعدة      = 11; // جرثومة المعدة
    case البشرة_والشعر      = 12; // البشرة والشعر
    case فشل_كلوي           = 13; // فشل كلوي
    case إبر_التخسيس        = 14; // إبر التخسيس
    case تعيين_جنس_الجنين   = 15; // تعيين جنس الجنين
    case تكيس               = 16; // تكيس
    case الحمل_والرضاعة     = 17; // الحمل والرضاعة
    case كيتو               = 18; // كيتو

    public function label(): string
    {
        return match($this) {
            self::عادي               => 'ما عندي أي مشكلة',
            self::عالي_البروتين      => 'أبي أزيد بروتين',
            self::نباتي              => 'أنا نباتي',
            self::LiverHealth        => 'وجبات لصحة الكبد',
            self::السكري             => 'سكري',
            self::مشاكل_القولون      => 'مشاكل قولون',
            self::ارتفاع_الكوليسترول => 'ارتفاع كوليسترول',
            self::فقر_الدم           => 'فقر دم / نقص حديد',
            self::التصلب_المتعدد     => 'تصلب متعدد (MS)',
            self::برنامج_٢١_يوم      => 'برنامج 21 يوم',
            self::جرثومة_المعدة      => 'جرثومة المعدة',
            self::البشرة_والشعر      => 'البشرة والشعر',
            self::فشل_كلوي           => 'فشل كلوي',
            self::إبر_التخسيس        => 'إبر التخسيس',
            self::تعيين_جنس_الجنين   => 'تعيين جنس الجنين',
            self::تكيس               => 'تكيس',
            self::الحمل_والرضاعة     => 'الحمل والرضاعة',
            self::كيتو               => 'كيتو',
        };
    }

    public function description(): string
    {
        return match($this) {
            self::عادي               => 'أبي نظام عادي يناسب ثقافة أكلي',
            self::عالي_البروتين      => 'نظام عالي البروتين للعضلات والشبع',
            self::نباتي              => 'نظام كامل بدون منتجات حيوانية',
            self::LiverHealth        => 'دعم صحة الكبد والحفاظ على وظائفه',
            self::السكري             => 'نظام يوازن السكر ويحافظ على الطاقة',
            self::مشاكل_القولون      => 'انتفاخ، غازات، تهيّج قولون',
            self::ارتفاع_الكوليسترول => 'نظام يقلل الدهون الضارة',
            self::فقر_الدم           => 'برنامج غني بالحديد و الفيتامينات',
            self::التصلب_المتعدد     => 'دعم الطاقة والمناعة',
            self::برنامج_٢١_يوم      => 'خسارة وزن سريعة بشكل آمن',
            self::جرثومة_المعدة      => 'نظام يريّح المعدة ويخفف الحموضة والالتهاب',
            self::البشرة_والشعر      => 'نظام غني بالفيتامينات لصحة البشرة والشعر',
            self::فشل_كلوي           => 'نظام يخفف الحمل على الكلى',
            self::إبر_التخسيس        => 'نظام مناسب لمستخدمي إبر التخسيس',
            self::تعيين_جنس_الجنين   => 'نظام غذائي يساعد في تعيين جنس الجنين',
            self::تكيس               => 'نظام يوازن الهرمونات ويساعد مع التكيس',
            self::الحمل_والرضاعة     => 'تغذية متكاملة للأم والطفل',
            self::كيتو               => 'نظام قليل الكربوهيدرات وعالي الدهون الصحية',
        };
    }

    /**
     * نوع رژیم‌هایی (DietType) که ردیف کالری این نوع غذا از آن‌ها خوانده می‌شود، به ترتیب اولویت.
     * انواعی که معادل ندارند (مثل عادي) آرایه خالی برمی‌گردانند تا از هدف وزنی کاربر استفاده شود.
     */
    public function dietTypes(?int $userDietTypeId): array
    {
        return match($this) {
            self::السكري        => [DietType::دیابت],
            self::مشاكل_القولون => $userDietTypeId === DietType::افزایش_وزن->value
                ? [DietType::سندرم_روده_تحریک_پذیر_افزایشی, DietType::سندرم_روده_تحریک_پذیر]
                : [DietType::سندرم_روده_تحریک_پذیر],
            self::برنامج_٢١_يوم => [DietType::رژیم_۲۱_روزه, DietType::رژیم_مدیترانه‌ای],
            self::الحمل_والرضاعة => [DietType::بارداری],
            self::كيتو          => [DietType::کتو],
            default             => [],
        };
    }

    public static function getList(): array
    {
        return array_map(fn($case) => [
            'id' => $case->value,
            'label' => $case->label(),
            'description' => $case->description(),
        ], self::cases());
    }
}
